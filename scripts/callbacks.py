"""Generate closure trampolines for all gfx trace hooks and commit listeners."""
import json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
API=json.loads((ROOT/'scripts/api.json').read_text())
STRUCTS={d['name']:d for d in API['gfx'] if d['kind']=='struct'}
PRIM={'int':('Int','int32_t'),'bool':('Bool','int32_t'),'uint32_t':('UInt','uint32_t'),'float':('Float','float'),'size_t':('UInt64','uint64_t')}
def ty(t):return ''.join(w.capitalize() for w in t.removeprefix('sg_').split('_'))
def argtype(t):
 b=t.removeprefix('const ').removesuffix(' *')
 if b in STRUCTS:return ty(b),'mb_box *',b
 if t=='const char *':return 'Bytes','moonbit_bytes_t',None
 if t in PRIM:return *PRIM[t],None
 raise ValueError(t)
def generate():
 mb=['// Generated by scripts/callbacks.py. Do not edit.'];c=['/* Generated closure trampolines. */']
 for n in ['sg_trace_hooks','sg_commit_listener']:
  d=STRUCTS[n];callbacks=[f for f in d['fields'] if '(*)' in f['type']]
  count=len(callbacks);st=ty(n);ctx=f'mb_{n}_callbacks'
  c.append(f'typedef struct {{ void *closure[{count}]; void *call[{count}]; }} {ctx};')
  for i,f in enumerate(callbacks):
   fn=f['name'];sig=f['type'];params=sig.split('(*)(')[1].removesuffix(')').split(', ')
   assert params[-1]=='void *', (fn,params)
   params=params[:-1]
   normalized=[argtype(t) for t in params]
   cb=f'mb_{n}_{fn}_call';tramp=f'mb_{n}_{fn}_trampoline';setter=f'mb_{n}_on_{fn}'
   c.append(f'typedef void (*{cb})(void*'+''.join(', '+ct for mt,ct,b in normalized)+');')
   cparams=', '.join(t+f' a{k}' for k,t in enumerate(params))+(', ' if params else '')+'void *userdata'
   body=[f'{ctx} *ctx=userdata;']
   args=[]
   for k,(t,(mt,ct,b)) in enumerate(zip(params,normalized)):
    a=f'a{k}'
    if b:
     val=f'*{a}' if '*' in t else a
     body.append(f'mb_box *b{k}=mb_box_new(sizeof({b})); {b} v{k}={val}; mb_clone_{b}(b{k}->arena,b{k}->value,&v{k});')
     args.append(f'b{k}')
    elif t=='const char *':args.append(f'mb_utf8({a})')
    else:args.append(a)
   body.append(f'moonbit_incref(ctx->closure[{i}]); (({cb})ctx->call[{i}])(ctx->closure[{i}]'+''.join(', '+a for a in args)+');')
   c.append(f'static void {tramp}({cparams}) {{ '+ ' '.join(body)+' }')
   # Detect our own context by comparing callbacks; never inspect arbitrary native userdata.
   detect=' || '.join(f'v->{ff["name"]}==mb_{n}_{ff["name"]}_trampoline' for ff in callbacks)
   # Implement setter after all trampoline declarations have been emitted.
   ctypes='void *closure'
   checks=' '.join(f'if(v->{ff["name"]} && v->{ff["name"]}!=mb_{n}_{ff["name"]}_trampoline) abort();' for ff in callbacks)
   setterbody=f'mb_box *r=mb_box_copy(self,sizeof({n})); {n} *v=r->value; {checks} {ctx} *ctx=mb_alloc(r->arena,sizeof(*ctx)); if({detect}) *ctx=*({ctx}*)v->user_data; ctx->closure[{i}]=closure; ctx->call[{i}]=(void*)call; mb_track(r->arena,closure,mb_closure_drop); v->user_data=ctx; v->{fn}={tramp}; return r;'
   c.append(('SETTER',f'MOONBIT_FFI_EXPORT mb_box *{setter}(mb_box *self,{cb} call,void *closure) {{ {setterbody} }}'))
   safe_types=['String' if t=='const char *' else mt for t,(mt,ct,b) in zip(params,normalized)]
   safe_cb='(' + ', '.join(safe_types) + ') -> Unit'
   ffi_cb='(' + ', '.join(mt for mt,ct,b in normalized) + ') -> Unit'
   bridge='FuncRef[('+safe_cb+''.join(', '+mt for mt,ct,b in normalized)+') -> Unit]'
   mb+=['','///|','#borrow(value)\n#owned(callback)\n'+f'extern "c" fn {n}_on_{fn}_ffi(value : {st}, call : {bridge}, callback : {safe_cb}) -> {st} = "{setter}"']
   names=[f'a{k}' for k in range(len(params))]
   args=[f'@utf8.decode_lossy(a{k})' if t=='const char *' else f'a{k}' for k,t in enumerate(params)]
   mb+=['','///|',f'pub fn {st}::on_{fn}(self : {st}, callback : {safe_cb}) -> {st} {{\n  {n}_on_{fn}_ffi(self, fn(f'+''.join(', '+a for a in names)+') { f('+', '.join(args)+') }, callback)\n}']
  # Emit all setters only after trampoline definitions.
  setters=[x[1] for x in c if isinstance(x,tuple)];c=[x for x in c if isinstance(x,str)]+setters
 c+=['''MOONBIT_FFI_EXPORT mb_box *mb_gfx_install_trace_hooks(mb_box *hooks) {
    sg_trace_hooks old=sg_install_trace_hooks(hooks->value);
    mb_box *r=mb_box_new(sizeof(old)); *(sg_trace_hooks*)r->value=old;
    mb_keep(r->arena,mb_lookup(UINT64_MAX)); mb_store(UINT64_MAX,hooks->arena); return r;
}
typedef struct mb_listener_entry {
    sg_commit_listener listener;
    mb_arena *arena;
    struct mb_listener_entry *next;
} mb_listener_entry;
static mb_listener_entry *mb_listeners;
MOONBIT_FFI_EXPORT int32_t mb_gfx_add_commit_listener(mb_box *listener) {
    sg_commit_listener l=*(sg_commit_listener*)listener->value;
    int ok=sg_add_commit_listener(l);
    if(ok) {
        mb_listener_entry *e=mb_malloc(sizeof(*e)); e->listener=l;
        e->arena=listener->arena; e->arena->refs++; e->next=mb_listeners; mb_listeners=e;
    }
    return ok;
}
MOONBIT_FFI_EXPORT int32_t mb_gfx_remove_commit_listener(mb_box *listener) {
    sg_commit_listener l=*(sg_commit_listener*)listener->value;
    int ok=sg_remove_commit_listener(l);
    if(ok) {
        mb_listener_entry **link=&mb_listeners;
        while(*link) {
            mb_listener_entry *e=*link;
            if(e->listener.func==l.func && e->listener.user_data==l.user_data) {
                *link=e->next; mb_arena_drop(e->arena); free(e); break;
            }
            link=&e->next;
        }
    }
    return ok;
}
MOONBIT_FFI_EXPORT void mb_gfx_shutdown(void) {
    sg_shutdown();
    while(mb_listeners) { mb_listener_entry *e=mb_listeners; mb_listeners=e->next; mb_arena_drop(e->arena); free(e); }
    mb_release_all();
}
MOONBIT_FFI_EXPORT int32_t mb_gfx_headless(void) {
#ifdef SOKOL_DUMMY_BACKEND
    return 1;
#else
    return 0;
#endif
}
''']
 mb+=['''
///|
#borrow(hooks)
extern "c" fn install_trace_hooks_ffi(hooks : TraceHooks) -> TraceHooks = "mb_gfx_install_trace_hooks"

///|
/// Install hooks and return the previous snapshot. Safe closure hooks must be
/// constructed with on_* methods; do not mix them with raw native callbacks.
pub fn install_trace_hooks(hooks : TraceHooks) -> TraceHooks { install_trace_hooks_ffi(hooks) }

///|
#borrow(listener)
extern "c" fn add_commit_listener_ffi(listener : CommitListener) -> Bool = "mb_gfx_add_commit_listener"

///|
pub fn add_commit_listener(listener : CommitListener) -> Bool { add_commit_listener_ffi(listener) }

///|
#borrow(listener)
extern "c" fn remove_commit_listener_ffi(listener : CommitListener) -> Bool = "mb_gfx_remove_commit_listener"

///|
pub fn remove_commit_listener(listener : CommitListener) -> Bool { remove_commit_listener_ffi(listener) }

///|
extern "c" fn shutdown_ffi() = "mb_gfx_shutdown"

///|
/// Destroy the graphics context after explicitly destroying GPU resources.
pub fn shutdown() -> Unit { shutdown_ffi() }

///|
extern "c" fn headless_ffi() -> Bool = "mb_gfx_headless"

///|
pub fn is_headless() -> Bool { headless_ffi() }
''']
 (ROOT/'gfx/callbacks.mbt').write_text('\n'.join(mb)+'\n')
 (ROOT/'gfx/callbacks.h').write_text('\n'.join(c)+'\n')
if __name__=='__main__':generate()
